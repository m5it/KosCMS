/**
 * MODIFIED: Enhanced documentation
 * Calculates sum with validation
 * @param {number} a First operand
 * @param {number} b Second operand
 * @returns {number} Sum or NaN if invalid
 * @throws {TypeError} If arguments not numbers
 * @since 2.0.0
 */
function add(a, b) {
    return a + b;
}

module.exports = { add };